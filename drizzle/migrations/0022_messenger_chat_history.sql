-- Store Messenger conversations separately for each shop customer.
-- The owner_id + psid pair keeps one customer's history isolated from every other customer.
CREATE TABLE IF NOT EXISTS public.messenger_chat_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id uuid NOT NULL,
  psid text NOT NULL,
  role text NOT NULL CHECK (role IN ('customer', 'shop')),
  message text NOT NULL,
  context jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS messenger_chat_messages_customer_time_idx
  ON public.messenger_chat_messages (owner_id, psid, created_at DESC);

GRANT ALL ON public.messenger_chat_messages TO service_role;
ALTER TABLE public.messenger_chat_messages ENABLE ROW LEVEL SECURITY;

-- Customer messages arrive through the service webhook, so service_role is the only
-- role that needs direct access to this private conversation table.
